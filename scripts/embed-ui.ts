// Writes src/api/ui-assets.gen.ts: one `with { type: "file" }` import per file of the UI export (ui/out),
// so `bun build --compile` embeds them in the binary. Inline script hashes for the CSP are computed here.
// Run after `bun run --cwd ui build`.
import { existsSync, writeFileSync } from "node:fs";
import { join, relative } from "node:path";
import { scanUiDir } from "../src/api/assets.ts";

const root = join(import.meta.dir, "..");
const out = join(root, "ui", "out");
const target = join(root, "src", "api", "ui-assets.gen.ts");

if (!existsSync(join(out, "index.html"))) {
  console.error("ui/out/index.html is missing. Build the UI first: bun run build:ui");
  process.exit(1);
}

const assets = scanUiDir(out);
const lines = [
  "// Generated by scripts/embed-ui.ts. Do not edit.",
  "// @ts-nocheck: file imports of any type (.ico, .html) resolve to embedded paths at build time.",
  'import type { UiAssets } from "./assets.ts";',
];
const entries: string[] = [];
Object.entries(assets)
  .sort(([a], [b]) => a.localeCompare(b))
  .forEach(([urlPath, a], i) => {
    const rel = relative(join(root, "src", "api"), a.file).split("\\").join("/");
    lines.push(`import f${i} from ${JSON.stringify(rel)} with { type: "file" };`);
    entries.push(
      `  ${JSON.stringify(urlPath)}: { file: f${i}, type: ${JSON.stringify(a.type)}${
        a.scriptHashes ? `, scriptHashes: ${JSON.stringify(a.scriptHashes)}` : ""
      } },`,
    );
  });
lines.push("", "export const assets: UiAssets = {", ...entries, "};", "");
writeFileSync(target, lines.join("\n"));
console.log(`Embedded ${entries.length} UI files in ${relative(root, target)}`);
