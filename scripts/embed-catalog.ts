// Writes src/catalog/snapshot.gen.ts: the signed catalog the website built, as base64, so
// `bun build --compile` bundles it. Embeds nothing (snapshot = null) when the files are missing
// or do not verify against CATALOG_PUBLIC_KEYS. Usage: bun scripts/embed-catalog.ts [catalog.json]
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { join, relative, resolve } from "node:path";
import { CATALOG_PUBLIC_KEYS } from "../src/catalog/key.ts";
import { CatalogError, verifyCatalog } from "../src/catalog/verify.ts";

const root = join(import.meta.dir, "..");
const source = resolve(process.argv[2] ?? join(root, "website", "public", "catalog", "v1", "catalog.json"));
const sigFile = `${source}.sig`;
const target = join(root, "src", "catalog", "snapshot.gen.ts");

async function pick(): Promise<{ catalog: string; sig: string } | null> {
  if (!existsSync(source) || !existsSync(sigFile)) {
    console.warn(`No catalog snapshot: ${relative(root, source)} or its .sig is missing.`);
    return null;
  }
  const bytes = new Uint8Array(readFileSync(source));
  const sig = readFileSync(sigFile, "utf8");
  try {
    const file = await verifyCatalog(bytes, sig, { keys: CATALOG_PUBLIC_KEYS });
    console.log(`Embedding catalog serial ${file.serial} (${bytes.byteLength} bytes).`);
    return { catalog: Buffer.from(bytes).toString("base64"), sig: Buffer.from(sig).toString("base64") };
  } catch (err) {
    const why = err instanceof CatalogError ? err.message : "it could not be read";
    console.warn(`No catalog snapshot: ${relative(root, source)} does not verify (${why})`);
    return null;
  }
}

const snap = await pick();
writeFileSync(
  target,
  [
    "// Generated by scripts/embed-catalog.ts. Do not edit.",
    `export const snapshot: { catalog: string; sig: string } | null = ${JSON.stringify(snap)};`,
    "",
  ].join("\n"),
);
console.log(`Wrote ${relative(root, target)}`);
